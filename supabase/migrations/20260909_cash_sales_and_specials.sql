  add column if not exists payment_method text not null default 'card',
  add column if not exists cash_received_at timestamptz,
  add column if not exists stripe_invoice_id text;

alter table public.orders drop constraint if exists orders_payment_method_check;
alter table public.orders add constraint orders_payment_method_check check (payment_method in ('card', 'cash'));
create unique index if not exists orders_stripe_invoice_id_key on public.orders (stripe_invoice_id) where stripe_invoice_id is not null;

create table if not exists public.specials (
  id bigint generated by default as identity primary key,
  title text not null,
  qualifying_quantity integer not null check (qualifying_quantity between 2 and 100),
  qualifying_unit_price_in_cents integer not null check (qualifying_unit_price_in_cents between 1 and 99999),
  bundle_price_in_cents integer not null check (bundle_price_in_cents between 1 and 999999),
  stripe_product_id text,
  stripe_price_id text,
  is_active boolean not null default true,
  updated_at timestamptz not null default now(),
  constraint special_is_discount check (bundle_price_in_cents < qualifying_quantity * qualifying_unit_price_in_cents)
);

create unique index if not exists one_active_special on public.specials (is_active) where is_active;
alter table public.specials enable row level security;
revoke all on public.specials from anon, authenticated;
grant select on public.specials to anon, authenticated;
drop policy if exists "Anyone can view the active special" on public.specials;
create policy "Anyone can view the active special" on public.specials for select to anon, authenticated using (is_active);
drop policy if exists "Admins can view all specials" on public.specials;
create policy "Admins can view all specials" on public.specials for select to authenticated using (exists (select 1 from public.admin_users where user_id=auth.uid()));

